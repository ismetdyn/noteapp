#!/usr/bin/env bash
# Günlük kullanım için yerel kurulum: FUSE bağlaması yok, `notes` AppImage'dan altı kat hızlı açılır (README).
# Kaynak AppImage dosyası ya da `cmake --install` ağacıdır. Yalnız şunlara yazar:
#   ~/.local/share/noteapp/<sürüm>/    paketin kendisi; aynı sürüm yeniden kurulunca değişir
#   ~/.local/bin/{note,notes,notes-gui} bu dizine symlink
#   zsh/bash tamamlama dosyaları (`note completion`): yalnız kendi ürettiğimizin üzerine yazılır
#   ~/.local/share/applications/noteapp.desktop ve icons/hicolor/*/apps/noteapp.*: GUI'li pakette menü girdisi
# Kullanım: scripts/install-local.sh [seçenekler] <noteapp-*.AppImage | cmake-install-dizini> | --uninstall
# Güncelleme seçenekleri (app::install_update çağırır; betik pakette usr/share/noteapp/ altındadır):
#   --keep N              kurulumdan sonra en yeni N sürüm dizini kalır; az önce kurulan, kurulumdan önce `note`
#                         bağının gösterdiği ve bu betiği taşıyan (çalışan) sürüm de her zaman kalır. Kabuk kurulum
#                         rehberi basılmaz: kullanıcı zaten kurulu, etkileşimli zsh yoklaması da çağıranın (TUI)
#                         terminaline dokunabilir.
#   --expect-version V    paket başka sürüm bildirirse hiçbir şey değişmeden düşer
#   --progress-dir DIR    stderr DIR/stderr.log'a eklenir; değiştirmeye başlamadan DIR/committing, bağlar yeni
#                         sürüme dönünce DIR/committed yaratılır (çağıran ikisinin arasında iptal etmez: yarım
#                         kalmış bağ bırakmasın; sonraki isteğe bağlı adımlar takılırsa durdurabilir)
# Menü girdisi, ikonlar, tamamlama ve eski sürüm temizliği isteğe bağlıdır: düşmeleri uyarıdır, kurulum başarılır.
# ~/.local/share/noteapp aynı zamanda veri dizinidir (graph.db, geçiş yedekleri): dizin bütünüyle silinmez.
set -euo pipefail

die() { echo "ERROR: $*" >&2; exit 1; }

usage="usage: $0 [--keep N] [--expect-version V] [--progress-dir DIR] <AppImage | cmake install prefix> | --uninstall"
keep_versions=""
expect_version=""
progress_dir=""
while [[ $# -gt 1 ]]; do
    [[ $# -gt 2 ]] || die "$usage"
    case "$1" in
        --keep)
            [[ "$2" =~ ^[1-9][0-9]*$ ]] || die "--keep needs a positive number: $2"
            keep_versions="$2"
            ;;
        --expect-version) expect_version="$2" ;;
        --progress-dir)
            [[ -d "$2" ]] || die "--progress-dir needs an existing directory: $2"
            progress_dir="$2"
            ;;
        *) die "$usage" ;;
    esac
    shift 2
done
[[ $# -eq 1 ]] || die "$usage"
if [[ -n "$progress_dir" ]]; then
    exec 2>>"$progress_dir/stderr.log"
fi
: "${HOME:?HOME is required}"

share="$HOME/.local/share/noteapp"
bin="$HOME/.local/bin"
readonly stale_staging_minutes=60

# Kullanıcıya özel standart yerler: bash-completion önce BASH_COMPLETION_USER_DIR'e (ilk girdi), yoksa
# XDG_DATA_HOME/bash-completion'a bakar; zsh'in standart kullanıcı dizini yok, README fpath satırını anlatır.
data_home="${XDG_DATA_HOME:-$HOME/.local/share}"
bash_completion_dir="${BASH_COMPLETION_USER_DIR:-$data_home/bash-completion}"
completion_files=("zsh:$data_home/zsh/site-functions/_note" "bash:${bash_completion_dir%%:*}/completions/note")
# `note completion` çıktısının başlığında durur: dosyanın bizim olduğunu söyler.
readonly completion_marker='Generated by `note completion'
# Etkileşimli zsh .zshrc'yi (oh-my-zsh dahil) yükler; takılırsa kurulumu bekletmesin.
readonly zsh_probe_seconds=5

# Menü girdisi tek kaynaktan türer (AppImage de bunu taşır); işaret satırı dosyanın bizim olduğunu söyler. Pakette
# betiğin yanına kopyalanır (packaging/linux/build-in-container.sh), depoda packaging/linux altındadır.
script_dir="$(dirname -- "$(realpath -- "$0")")"
desktop_template="$script_dir/noteapp.desktop"
if [[ ! -f "$desktop_template" ]]; then
    desktop_template="$script_dir/../packaging/linux/noteapp.desktop"
fi
readonly desktop_marker='X-Noteapp-Installer=install-local.sh'
desktop_file="$data_home/applications/noteapp.desktop"
hicolor_dir="$data_home/icons/hicolor"
# İkon dosyasına işaret konamaz: kurduğumuz ikonların yolu burada tutulur, yalnız bunlar ezilir ve silinir.
icon_list="$share/desktop-icons.list"

is_our_completion() {
    [[ -f "$1" && ! -L "$1" ]] && grep -qF -- "$completion_marker" "$1"
}

# Kurulan `note` betiği üretir. Tamamlaması olmayan eski paket ya da yabancı dosya kurulumu düşürmez, söylenir.
install_completions() {
    local entry shell file script
    for entry in "${completion_files[@]}"; do
        shell="${entry%%:*}"
        file="${entry#*:}"
        if [[ -e "$file" || -L "$file" ]] && ! is_our_completion "$file"; then
            echo "not ours, left in place: $file" >&2
            continue
        fi
        if ! script="$("$bin/note" completion "$shell" 2>/dev/null)" || [[ "$script" != *"$completion_marker"* ]]; then
            echo "this package has no $shell completion, skipped: $file" >&2
            continue
        fi
        mkdir -p -- "${file%/*}" && printf '%s\n' "$script" >"$file.new" && mv -f -- "$file.new" "$file" ||
            return 1
    done
}

uninstall_completions() {
    local entry file
    for entry in "${completion_files[@]}"; do
        file="${entry#*:}"
        if is_our_completion "$file"; then
            rm -- "$file"
        elif [[ -e "$file" || -L "$file" ]]; then
            echo "not ours, left in place: $file" >&2
        fi
    done
}

is_our_desktop_file() {
    [[ -f "$1" && ! -L "$1" ]] && grep -qxF -- "$desktop_marker" "$1"
}

is_our_icon() {
    [[ -f "$1" && ! -L "$1" && -f "$icon_list" ]] && grep -qxF -- "$1" "$icon_list"
}

# Araç yoksa menü yine çalışır (oturum yenilenince); düşmesi kurulumu düşürmez.
refresh_desktop_caches() {
    if [[ -d "${desktop_file%/*}" ]] && command -v update-desktop-database >/dev/null; then
        update-desktop-database -q -- "${desktop_file%/*}" || echo "update-desktop-database failed" >&2
    fi
    if [[ -d "$hicolor_dir" ]] && command -v gtk-update-icon-cache >/dev/null; then
        gtk-update-icon-cache -f -t -q -- "$hicolor_dir" || echo "gtk-update-icon-cache failed" >&2
    fi
}

# Exec mutlak yolla kurulan bağı açar: bağ güncellemede yeni sürüme döner, girdi değişmez.
desktop_entry() {
    local line gui="$bin/notes-gui"
    while IFS= read -r line; do
        if [[ "$line" == Exec=notes-gui ]]; then
            printf 'TryExec=%s\nExec="%s"\n%s\n' "$gui" "$gui" "$desktop_marker"
        else
            printf '%s\n' "$line"
        fi
    done <"$desktop_template"
}

# $1: paket içindeki hicolor dizini. İkonsuz girdi menüde boş kare gösterir: hiç yazılmaz.
install_desktop_entry() {
    local source_dir="$1" icon relative destination
    local -a icons=()
    # Menü girdisi isteğe bağlı: yazılamıyorsa komutlar yine kurulur, yalnız girdi atlanır.
    if ! grep -qxF 'Exec=notes-gui' "$desktop_template" 2>/dev/null; then
        echo "warning: desktop entry skipped: no Exec=notes-gui line in $desktop_template" >&2
        return 0
    fi
    # Exec değeri tırnak içinde kaçışsız durabilmeli.
    if [[ "$bin" == *[\"\`\$\\%[:cntrl:]]* ]]; then
        echo "warning: desktop entry skipped: $bin path cannot be quoted in a .desktop Exec line" >&2
        return 0
    fi
    for icon in "$source_dir"/*/apps/noteapp.png "$source_dir"/scalable/apps/noteapp.svg; do
        if [[ -f "$icon" ]]; then
            icons+=("${icon#"$source_dir"/}")
        fi
    done
    if [[ ${#icons[@]} -eq 0 ]]; then
        echo "warning: no noteapp icon in $source_dir; menu entry not installed" >&2
        return 0
    fi
    for relative in "${icons[@]}"; do
        destination="$hicolor_dir/$relative"
        if [[ (-e "$destination" || -L "$destination") ]] && ! is_our_icon "$destination"; then
            echo "not ours, left in place: $destination" >&2
            continue
        fi
        mkdir -p -- "${destination%/*}" && cp -- "$source_dir/$relative" "$destination.new" &&
            mv -f -- "$destination.new" "$destination" || return 1
        if ! grep -qxF -- "$destination" "$icon_list" 2>/dev/null; then
            printf '%s\n' "$destination" >>"$icon_list" || return 1
        fi
    done
    if [[ (-e "$desktop_file" || -L "$desktop_file") ]] && ! is_our_desktop_file "$desktop_file"; then
        echo "not ours, left in place: $desktop_file" >&2
    else
        mkdir -p -- "${desktop_file%/*}" && desktop_entry >"$desktop_file.new" &&
            mv -f -- "$desktop_file.new" "$desktop_file" || return 1
    fi
    refresh_desktop_caches
}

uninstall_desktop_entry() {
    local icon
    if is_our_desktop_file "$desktop_file"; then
        rm -- "$desktop_file"
    elif [[ -e "$desktop_file" || -L "$desktop_file" ]]; then
        echo "not ours, left in place: $desktop_file" >&2
    fi
    if [[ -f "$icon_list" ]]; then
        while IFS= read -r icon; do
            if is_our_icon "$icon"; then
                rm -- "$icon"
            fi
        done <"$icon_list"
        rm -- "$icon_list"
    fi
    refresh_desktop_caches
}

# Bizim bağımız: hedef mutlak ve sürüm dizinimizin içinde. `..` hedefi dışarı kaçırabilir, sayılmaz.
is_our_link() {
    [[ -L "$1" ]] || return 1
    local link_target
    link_target="$(readlink -- "$1")"
    [[ "$link_target" == "$share"/* && "$link_target" != */../* ]]
}

# Sürüm dizini paketin çalıştırılabilirini kökte taşır; geçiş yedeği notları notes/ altında tutar, karışmaz.
is_version_dir() {
    [[ -d "$1" && ! -L "$1" && (-x "$1/AppRun" || -x "$1/bin/note") ]]
}

uninstall() {
    local name link dir
    for name in note notes notes-gui; do
        link="$bin/$name"
        if is_our_link "$link"; then
            rm -- "$link"
        elif [[ -e "$link" || -L "$link" ]]; then
            echo "not ours, left in place: $link" >&2
        fi
    done
    uninstall_completions
    uninstall_desktop_entry
    [[ -d "$share" ]] || return 0
    for dir in "$share"/* "$share"/.install.*; do
        if is_version_dir "$dir" || [[ -d "$dir" && "${dir##*/}" == .install.* ]]; then
            rm -rf -- "$dir"
        fi
    done
    # Yalnız boşsa kalkar: not verisi varsa dizin durur.
    if rmdir -- "$share" 2>/dev/null; then
        echo "uninstalled"
    else
        echo "uninstalled; your notes stay in: $share"
    fi
}

# $1: yol (bağ çözülür); sürüm dizinimizin içindeyse o dizinin adı, değilse boş.
version_of() {
    local share_real path_real relative
    share_real="$(realpath -m -- "$share")"
    path_real="$(realpath -m -- "$1")"
    [[ "$path_real" == "$share_real"/*/* ]] || return 0
    relative="${path_real#"$share_real"/}"
    printf '%s' "${relative%%/*}"
}

# --keep: en yeni $1 sürüm dizini (sort -V) ve korunanlar kalır. Veri (graph.db, yedekler) sürüm dizini değildir.
prune_versions() {
    local keep="$1" dir name kept=0 status=0
    shift
    local -a names=()
    for dir in "$share"/*; do
        if is_version_dir "$dir"; then
            names+=("${dir##*/}")
        fi
    done
    [[ ${#names[@]} -gt 0 ]] || return 0
    while IFS= read -r name; do
        if [[ $kept -lt $keep ]]; then
            kept=$((kept + 1))
        elif [[ " $* " != *" $name "* ]] && is_version_dir "$share/$name"; then
            rm -rf -- "${share:?}/$name" || status=1
        fi
    done < <(printf '%s\n' "${names[@]}" | sort -rV)
    return "$status"
}

# rc dosyasına kopyalanacak yol: HOME altındaysa "$HOME/..." (bash ve zsh'te aynı), değilse tırnaklı mutlak yol.
rc_path() {
    if [[ "$1" == "$HOME"/* ]]; then
        printf '"%s/%s"' "\$HOME" "${1#"$HOME"/}"
    else
        printf '%q' "$1"
    fi
}

# Kullanıcının dotfile'larına yazılmaz: yalnız eksik olan satır, kopyalanabilir biçimde gösterilir.
print_shell_setup() {
    local zsh_dir="${completion_files[0]#*:}" login_shell fpath_dirs
    zsh_dir="${zsh_dir%/*}"
    if [[ ":$PATH:" != *":$bin:"* ]]; then
        echo "$bin is not in PATH; add this line to ~/.bashrc (bash) or ~/.zshrc (zsh), then open a new terminal:"
        echo "  export PATH=\"\$HOME/${bin#"$HOME"/}:\$PATH\""
    fi
    # Giriş kabuğu passwd'den; kurulum zsh içinden bash ile koşsa da doğru kalır.
    login_shell="$(getent passwd "$(id -un)" 2>/dev/null | cut -d: -f7)" || true
    login_shell="${login_shell:-${SHELL:-}}"
    if [[ "${login_shell##*/}" == zsh && -f "$zsh_dir/_note" ]]; then
        # Kullanıcının gerçek fpath'i yalnız .zshrc yüklendikten sonra belli olur. Yoklama düşerse talimat basılır.
        fpath_dirs="$(timeout "$zsh_probe_seconds" zsh -ic "print -rl -- \$fpath" </dev/null 2>/dev/null)" || fpath_dirs=""
        if ! grep -qxF -- "$zsh_dir" <<<"$fpath_dirs"; then
            echo "zsh does not look in $zsh_dir; add this line to ~/.zshrc before compinit"
            echo "(oh-my-zsh: before 'source \$ZSH/oh-my-zsh.sh'), then open a new terminal:"
            echo "  fpath=($(rc_path "$zsh_dir") \$fpath)"
        fi
    fi
    if [[ " ${commands[*]} " == *" notes-gui:"* ]]; then
        echo "tip: start the GUI without holding the terminal: setsid -f notes-gui >/dev/null 2>&1"
    fi
}

if [[ "$1" == --uninstall ]]; then
    uninstall
    exit 0
fi

source_path="$(realpath -- "$1")" || die "not found: $1"
mkdir -p "$share" "$bin"

# Kesilmiş kurulumun artığı. Taze olanı çalışan başka bir kuruluma ait olabilir.
find "$share" -mindepth 1 -maxdepth 1 -type d -name '.install.*' -mmin "+$stale_staging_minutes" \
    -exec rm -rf -- {} +

# Açılan paket özel dizinde kalır: paylaşılan /tmp'de başka kullanıcı önceden dizin yaratabilir (README).
# Aynı dosya sisteminde olması rename'i atomik yapar.
staging="$(mktemp -d "$share/.install.XXXXXX")"
cleanup() { rm -rf "$staging"; }
trap cleanup EXIT

# Paket kökünü ve üç komutun paket içindeki hedefini belirler.
if [[ -f "$source_path" ]]; then
    [[ -x "$source_path" ]] || die "not executable: $source_path"
    (cd "$staging" && "$source_path" --appimage-extract >/dev/null) || die "extracting failed: $source_path"
    package="$staging/squashfs-root"
    [[ -x "$package/AppRun" ]] || die "no AppRun in: $source_path"
    version_output="$("$package/AppRun" note --version)" || die "cannot read the version"
    # AppRun komutu symlink adından seçer, CA ayarını da o yapar.
    commands=(note:AppRun notes:AppRun notes-gui:AppRun)
    icon_source=usr/share/icons/hicolor
elif [[ -d "$source_path" ]]; then
    [[ -x "$source_path/bin/notes" && -x "$source_path/bin/note" ]] || die "no bin/notes and bin/note in: $source_path"
    package="$staging/tree"
    cp -a "$source_path" "$package"
    version_output="$("$package/bin/note" --version)" || die "cannot read the version"
    commands=(note:bin/note notes:bin/notes)
    icon_source=share/icons/hicolor
    if [[ -x "$source_path/bin/notes-gui" ]]; then
        commands+=(notes-gui:bin/notes-gui)
    fi
else
    die "neither a file nor a directory: $source_path"
fi

# Çıktı `note <sürüm>`: son sözcük. Yol olarak kullanılacağı için doğrulanır: `.`/`..` ve gizli ad (`.install.*`)
# sürüm dizini olamaz.
version="${version_output##* }"
[[ "$version" =~ ^[0-9A-Za-z][0-9A-Za-z.+_-]*$ ]] || die "unexpected version: $version_output"
if [[ -n "$expect_version" && "$version" != "$expect_version" ]]; then
    die "the package is version $version, expected $expect_version"
fi

# Güncellemede silinmeyecek sürümler: kurulumdan önce kullanılan ve bu betiği taşıyan (çalışan) sürüm.
protected_versions=("$(version_of "$0")")
if is_our_link "$bin/note"; then
    protected_versions+=("$(version_of "$(readlink -- "$bin/note")")")
fi

# Yalnız bizim bağımız değişir; yabancı dosya ve bağ ezilmez. Hiçbir şey değişmeden önce denetlenir.
for entry in "${commands[@]}"; do
    link="$bin/${entry%%:*}"
    if [[ (-e "$link" || -L "$link") ]] && ! is_our_link "$link"; then
        die "refusing to replace, not a noteapp link: $link (remove it yourself to install here)"
    fi
done

# Bundan sonrası değiştirir: çağıran artık iptal etmez.
if [[ -n "$progress_dir" ]]; then
    : >"$progress_dir/committing"
fi
target="$share/$version"
if [[ ! -e "$target" ]]; then
    mv -T -- "$package" "$target" || die "cannot move the package to: $target"
elif ! mv --exchange -T -- "$package" "$target" 2>/dev/null; then
    # coreutils < 9.5: --exchange yok. Dolu dizin üzerine rename olmaz: iki adım, ikincisi düşerse geri konur.
    # ponytail: arada kesilirse sürüm dizini bir an yok olur; atomik yol yalnız --exchange.
    previous="$staging/previous"
    mv -T -- "$target" "$previous" || die "cannot replace: $target"
    if ! mv -T -- "$package" "$target"; then
        mv -T -- "$previous" "$target"
        die "cannot move the package to: $target"
    fi
fi
for entry in "${commands[@]}"; do
    ln -sfn "$target/${entry#*:}" "$bin/${entry%%:*}"
done
if [[ -n "$progress_dir" ]]; then
    : >"$progress_dir/committed"
fi
# Komutlar kuruldu; aşağıdakiler isteğe bağlı. `||` içinde set -e kapalıdır: adımlar düşüşü kendileri döndürür.
install_completions || echo "warning: shell completions were not fully installed" >&2
if [[ " ${commands[*]} " == *" notes-gui:"* ]]; then
    install_desktop_entry "$target/$icon_source" || echo "warning: the menu entry was not fully installed" >&2
fi
echo "installed $version: $target"
if [[ -n "$keep_versions" ]]; then
    prune_versions "$keep_versions" "$version" "${protected_versions[@]}" ||
        echo "warning: some old versions were not removed from $share" >&2
else
    print_shell_setup
fi

#!/usr/bin/env bash
# scripts/install-local.sh: geçici HOME'da sahte kurulum ağacı ve sahte AppImage ile; gerçek HOME'a dokunmaz.
# Kullanım: install_local_test.sh <repo kökü>
set -euo pipefail

die() { echo "FAIL: $*" >&2; exit 1; }

script="$1/scripts/install-local.sh"
work="$(mktemp -d)"
cleanup() { rm -rf "$work"; }
trap cleanup EXIT
export HOME="$work/home"
mkdir -p "$HOME"
# Tamamlama dosyaları bunlara göre yerleşir: kullanıcının gerçek dizinine yazılmasın.
unset XDG_DATA_HOME BASH_COMPLETION_USER_DIR

fake_tree="$work/tree"
mkdir -p "$fake_tree/bin"
cat >"$fake_tree/bin/note" <<'EOF'
#!/bin/sh
case "$1" in
    completion) echo "# $2 completion for note. Generated by \`note completion $2\`; fake" ;;
    *) echo "note 9.8.7" ;;
esac
EOF
printf '#!/bin/sh\necho fake-notes\n' >"$fake_tree/bin/notes"
chmod +x "$fake_tree/bin/note" "$fake_tree/bin/notes"

bash "$script" "$fake_tree" >/dev/null
[[ "$("$HOME/.local/bin/notes")" == fake-notes ]] || die "notes symlink does not run the installed tree"
[[ "$(readlink "$HOME/.local/bin/note")" == "$HOME/.local/share/noteapp/9.8.7/bin/note" ]] || die "note symlink target"
[[ ! -e "$HOME/.local/bin/notes-gui" ]] || die "no gui in the tree, no link expected"
zsh_completion="$HOME/.local/share/zsh/site-functions/_note"
bash_completion="$HOME/.local/share/bash-completion/completions/note"
grep -qF 'Generated by `note completion zsh`' "$zsh_completion" || die "zsh completion not installed"
grep -qF 'Generated by `note completion bash`' "$bash_completion" || die "bash completion not installed"

# İdempotent: ikinci kurulum aynı sonucu verir ve kurulum artığı bırakmaz.
printf '#!/bin/sh\necho fake-notes-2\n' >"$fake_tree/bin/notes"
bash "$script" "$fake_tree" >/dev/null
[[ "$("$HOME/.local/bin/notes")" == fake-notes-2 ]] || die "reinstall did not replace the package"
[[ "$(ls -A "$HOME/.local/share/noteapp")" == 9.8.7 ]] || die "staging left behind"
grep -qF 'Generated by `note completion zsh`' "$zsh_completion" || die "zsh completion lost on reinstall"
[[ "$(ls -A "${zsh_completion%/*}")" == _note ]] || die "completion temp file left behind"

# Yabancı tamamlama dosyası ezilmez, kurulum yine başarılıdır.
echo mine >"$bash_completion"
bash "$script" "$fake_tree" >/dev/null 2>&1 || die "a foreign completion file must not fail the install"
[[ "$(cat "$bash_completion")" == mine ]] || die "foreign completion file was replaced"
rm "$bash_completion"
bash "$script" "$fake_tree" >/dev/null

# Yabancı dosya ezilmez, hata temiz çıkar.
rm "$HOME/.local/bin/notes"
echo mine >"$HOME/.local/bin/notes"
if bash "$script" "$fake_tree" >/dev/null 2>&1; then
    die "a regular file in ~/.local/bin must not be replaced"
fi
[[ "$(cat "$HOME/.local/bin/notes")" == mine ]] || die "regular file was changed"
rm "$HOME/.local/bin/notes"

# AppImage: komut symlink adından seçilir (AppRun).
fake_appimage="$work/noteapp.AppImage"
cat >"$fake_appimage" <<'EOF'
#!/bin/sh
[ "$1" = --appimage-extract ] || exit 2
mkdir -p squashfs-root
cat >squashfs-root/AppRun <<'INNER'
#!/bin/sh
case "${0##*/}:$1" in
    AppRun:note) echo "note 1.2.3" ;;
    notes:*) echo apprun-notes ;;
    *) exit 3 ;;
esac
INNER
chmod +x squashfs-root/AppRun
EOF
# Paket sözleşmesi (packaging/linux/build-in-container.sh): ikonlar usr/share/icons/hicolor altında.
repo_icons="$1/resources/icons"
printf 'mkdir -p %s %s\ncp %q %s\ncp %q %s\n' \
    squashfs-root/usr/share/icons/hicolor/16x16/apps squashfs-root/usr/share/icons/hicolor/scalable/apps \
    "$repo_icons/hicolor/16x16/apps/noteapp.png" squashfs-root/usr/share/icons/hicolor/16x16/apps/ \
    "$repo_icons/noteapp.svg" squashfs-root/usr/share/icons/hicolor/scalable/apps/ >>"$fake_appimage"
chmod +x "$fake_appimage"
bash "$script" "$fake_appimage" >/dev/null
[[ "$("$HOME/.local/bin/notes")" == apprun-notes ]] || die "AppImage notes link"
[[ -L "$HOME/.local/bin/notes-gui" ]] || die "AppImage gui link"
[[ "$(readlink "$HOME/.local/bin/notes-gui")" == "$HOME/.local/share/noteapp/1.2.3/AppRun" ]] || die "AppImage link target"

# Menü girdisi packaging/linux/noteapp.desktop'tan türer; Exec kurulan bağa mutlak yolla işaret eder.
desktop_file="$HOME/.local/share/applications/noteapp.desktop"
hicolor="$HOME/.local/share/icons/hicolor"
[[ -f "$desktop_file" ]] || die "desktop entry not installed"
grep -qxF 'Name=NoteApp' "$desktop_file" || die "desktop entry not derived from the packaged one"
grep -qxF "Exec=\"$HOME/.local/bin/notes-gui\"" "$desktop_file" || die "desktop Exec is not the installed link"
grep -qxF "TryExec=$HOME/.local/bin/notes-gui" "$desktop_file" || die "desktop TryExec"
grep -qxF 'X-Noteapp-Installer=install-local.sh' "$desktop_file" || die "desktop entry has no ownership marker"
if command -v desktop-file-validate >/dev/null; then
    desktop-file-validate "$desktop_file" || die "desktop-file-validate rejects the entry"
fi
cmp -s "$repo_icons/hicolor/16x16/apps/noteapp.png" "$hicolor/16x16/apps/noteapp.png" || die "png icon not installed"
cmp -s "$repo_icons/noteapp.svg" "$hicolor/scalable/apps/noteapp.svg" || die "svg icon not installed"
# İdempotent: aynı içerik, geçici dosya artığı yok.
desktop_before="$(cat "$desktop_file")"
bash "$script" "$fake_appimage" >/dev/null
[[ "$(cat "$desktop_file")" == "$desktop_before" ]] || die "reinstall changed the desktop entry"
[[ -z "$(find "$HOME/.local/share/applications" "$hicolor" -name '*.new')" ]] || die "desktop temp file left behind"

# Geçersiz girdi: açık hata.
if bash "$script" "$work/missing" >/dev/null 2>&1; then
    die "a missing source must fail"
fi

# İsteğe bağlı ikinci argüman: gerçek AppImage (ctest vermez), iki kez kurulur, komutlar paketten çalışır.
if [[ $# -ge 2 ]]; then
    bash "$script" "$2" >/dev/null
    bash "$script" "$2" >/dev/null
    "$HOME/.local/bin/note" --version | grep -q '^note ' || die "installed note does not run"
    readlink "$HOME/.local/bin/notes" | grep -q '/AppRun$' || die "notes link"
fi
# Sahiplik: yabancı bağa dokunulmaz, kurulum hiç başlamaz. Ayrı HOME: yukarıdaki durumdan bağımsız.
export HOME="$work/home-owner"
share="$HOME/.local/share/noteapp"
bin="$HOME/.local/bin"
mkdir -p "$bin" "$share"
ln -s /usr/bin/true "$bin/notes"
if refused="$(bash "$script" "$fake_tree" 2>&1)"; then
    die "a foreign link must not be replaced"
fi
[[ "$refused" == *"$bin/notes"* ]] || die "the refusal must name the link: $refused"
[[ "$(readlink "$bin/notes")" == /usr/bin/true ]] || die "foreign link was changed"
[[ ! -e "$bin/note" && ! -e "$share/9.8.7" ]] || die "a refused install changed something"
rm "$bin/notes"

# Eski kurulum artığı temizlenir, çalışan bir kurulumunki (taze) kalır.
mkdir "$share/.install.stale" "$share/.install.fresh"
touch -d '2 hours ago' "$share/.install.stale"
bash "$script" "$fake_tree" >/dev/null
[[ ! -e "$share/.install.stale" ]] || die "stale staging left behind"
[[ -d "$share/.install.fresh" ]] || die "a fresh staging directory may belong to a running install"
rmdir "$share/.install.fresh"
printf '#!/bin/sh\necho fake-notes-3\n' >"$fake_tree/bin/notes"

# Başarısız yeniden kurulum önceki kurulumu korur: paket bozuk ya da yerine koyma düşüyor.
broken_tree="$work/broken"
mkdir -p "$broken_tree/bin"
printf '#!/bin/sh\nexit 1\n' >"$broken_tree/bin/note"
printf '#!/bin/sh\nexit 1\n' >"$broken_tree/bin/notes"
chmod +x "$broken_tree/bin/note" "$broken_tree/bin/notes"
if bash "$script" "$broken_tree" >/dev/null 2>&1; then
    die "a package that cannot report its version must fail"
fi
[[ "$("$bin/notes")" == fake-notes-2 ]] || die "a broken package damaged the previous install"
failing_mv="$work/failing-mv"
mkdir -p "$failing_mv"
printf '#!/bin/sh\nexit 1\n' >"$failing_mv/mv"
chmod +x "$failing_mv/mv"
if PATH="$failing_mv:$PATH" bash "$script" "$fake_tree" >/dev/null 2>&1; then
    die "a failing rename must fail the install"
fi
[[ "$("$bin/notes")" == fake-notes-2 ]] || die "a failed rename lost the previous install"
[[ "$(ls -A "$share")" == 9.8.7 ]] || die "a failed install left files behind"
bash "$script" "$fake_tree" >/dev/null
[[ "$("$bin/notes")" == fake-notes-3 ]] || die "reinstall over a previous version"
[[ "$(ls -A "$share")" == 9.8.7 ]] || die "the replaced version stayed behind"

# coreutils < 9.5 (--exchange yok): iki adımlı yol. İkinci adım düşerse önceki kurulum geri konur.
real_mv="$(command -v mv)"
old_mv="$work/old-mv"
mkdir -p "$old_mv"
printf '#!/bin/sh\ncase "$*" in --exchange*) exit 1 ;; esac\nexec "%s" "$@"\n' "$real_mv" >"$old_mv/mv"
chmod +x "$old_mv/mv"
printf '#!/bin/sh\necho fake-notes-4\n' >"$fake_tree/bin/notes"
PATH="$old_mv:$PATH" bash "$script" "$fake_tree" >/dev/null
[[ "$("$bin/notes")" == fake-notes-4 ]] || die "install without mv --exchange"
[[ "$(ls -A "$share")" == 9.8.7 ]] || die "the two-step path left files behind"
printf '#!/bin/sh\ncase "$*" in --exchange*|*/tree*) exit 1 ;; esac\nexec "%s" "$@"\n' "$real_mv" >"$old_mv/mv"
printf '#!/bin/sh\necho fake-notes-5\n' >"$fake_tree/bin/notes"
if PATH="$old_mv:$PATH" bash "$script" "$fake_tree" >/dev/null 2>&1; then
    die "a failing second step must fail the install"
fi
[[ "$("$bin/notes")" == fake-notes-4 ]] || die "the second step's failure lost the previous install"
[[ "$(ls -A "$share")" == 9.8.7 ]] || die "the second step's failure left files behind"

# --uninstall: yalnız bizim bağlar ve sürüm dizinleri. Bu dizin notların da evidir (README "Yapılandırma").
bash "$script" "$fake_appimage" >/dev/null
rm "$bin/notes-gui"
ln -s /usr/bin/true "$bin/notes-gui"
echo notes >"$share/graph.db"
mkdir -p "$share/migration-backup-1/notes/bin"
echo mine >"$share/migration-backup-1/notes/bin/note"
chmod +x "$share/migration-backup-1/notes/bin/note"
# Tamamlamasız paket (sahte AppImage) önceki kurulumun tamamlama dosyasını bırakır; kaldırma yalnız bizimkini siler.
grep -qF 'Generated by `note completion zsh`' "$HOME/.local/share/zsh/site-functions/_note" ||
    die "an install without completion removed the previous one"
echo mine >"$HOME/.local/share/bash-completion/completions/note"
bash "$script" --uninstall >/dev/null 2>&1
[[ ! -e "$HOME/.local/share/zsh/site-functions/_note" ]] || die "uninstall left our zsh completion"
[[ "$(cat "$HOME/.local/share/bash-completion/completions/note")" == mine ]] ||
    die "uninstall touched a foreign completion file"
[[ ! -L "$bin/note" && ! -L "$bin/notes" ]] || die "our links stayed"
[[ ! -e "$HOME/.local/share/applications/noteapp.desktop" ]] || die "uninstall left our desktop entry"
[[ ! -e "$HOME/.local/share/icons/hicolor/16x16/apps/noteapp.png" ]] || die "uninstall left our png icon"
[[ ! -e "$HOME/.local/share/icons/hicolor/scalable/apps/noteapp.svg" ]] || die "uninstall left our svg icon"
[[ "$(readlink "$bin/notes-gui")" == /usr/bin/true ]] || die "uninstall touched a foreign link"
[[ ! -e "$share/9.8.7" && ! -e "$share/1.2.3" ]] || die "version directories stayed"
[[ "$(cat "$share/graph.db")" == notes ]] || die "uninstall touched the notes database"
[[ "$(cat "$share/migration-backup-1/notes/bin/note")" == mine ]] || die "uninstall touched a backup"
bash "$script" --uninstall >/dev/null || die "a second uninstall must succeed"

# Boşalan dizin kalkar; hiç kurulmamışken hata yok, dizin de yaratılmaz.
export HOME="$work/home-clean"
mkdir -p "$HOME"
bash "$script" --uninstall >/dev/null || die "uninstall with nothing installed must succeed"
[[ ! -e "$HOME/.local/share/noteapp" ]] || die "uninstall created the directory"
bash "$script" "$fake_tree" >/dev/null
bash "$script" --uninstall >/dev/null
[[ ! -e "$HOME/.local/share/noteapp" ]] || die "the emptied directory stayed"

# Yabancı menü girdisi ve ikon ezilmez, kaldırmada da kalır; kurulum yine başarılıdır.
export HOME="$work/home-desktop"
apps="$HOME/.local/share/applications"
hicolor="$HOME/.local/share/icons/hicolor"
mkdir -p "$apps" "$hicolor/16x16/apps"
echo mine >"$apps/noteapp.desktop"
echo mine >"$hicolor/16x16/apps/noteapp.png"
bash "$script" "$fake_appimage" >/dev/null 2>&1 || die "a foreign desktop entry must not fail the install"
[[ "$(cat "$apps/noteapp.desktop")" == mine ]] || die "foreign desktop entry was replaced"
[[ "$(cat "$hicolor/16x16/apps/noteapp.png")" == mine ]] || die "foreign icon was replaced"
[[ -f "$hicolor/scalable/apps/noteapp.svg" ]] || die "a free icon slot must still be filled"
bash "$script" --uninstall >/dev/null 2>&1
[[ "$(cat "$apps/noteapp.desktop")" == mine ]] || die "uninstall touched a foreign desktop entry"
[[ "$(cat "$hicolor/16x16/apps/noteapp.png")" == mine ]] || die "uninstall touched a foreign icon"
[[ ! -e "$hicolor/scalable/apps/noteapp.svg" ]] || die "uninstall left our svg icon"
[[ ! -e "$HOME/.local/share/noteapp" ]] || die "uninstall left the icon list behind"

# cmake install ağacı: ikon aynı hicolor düzeninde share/ altında; yoksa girdi ikonsuz yazılmaz, uyarılır.
export HOME="$work/home-tree-gui"
gui_tree="$work/tree-gui"
cp -a "$fake_tree" "$gui_tree"
printf '#!/bin/sh\necho fake-gui\n' >"$gui_tree/bin/notes-gui"
chmod +x "$gui_tree/bin/notes-gui"
warning="$(bash "$script" "$gui_tree" 2>&1 >/dev/null)" || die "a tree without icons must still install"
[[ "$warning" == *icon* ]] || die "a missing icon must be reported: $warning"
[[ ! -e "$HOME/.local/share/applications/noteapp.desktop" ]] || die "desktop entry written without an icon"
mkdir -p "$gui_tree/share/icons/hicolor/48x48/apps"
cp "$repo_icons/hicolor/48x48/apps/noteapp.png" "$gui_tree/share/icons/hicolor/48x48/apps/"
bash "$script" "$gui_tree" >/dev/null
[[ -f "$HOME/.local/share/applications/noteapp.desktop" ]] || die "desktop entry from a cmake tree"
cmp -s "$repo_icons/hicolor/48x48/apps/noteapp.png" "$HOME/.local/share/icons/hicolor/48x48/apps/noteapp.png" ||
    die "icon from a cmake tree"
bash "$script" --uninstall >/dev/null
[[ ! -e "$HOME/.local/share/applications/noteapp.desktop" && ! -e "$HOME/.local/share/noteapp" ]] ||
    die "uninstall after a cmake tree install"
echo ok

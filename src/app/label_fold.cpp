FoldedCodepoints fold_codepoint(char32_t codepoint) {
    if (codepoint <= 0x7F)
        return {{codepoint >= 'A' && codepoint <= 'Z' ? codepoint + ('a' - 'A') : codepoint}, 1};
    for (const FoldMap& fold : kMaps) {
        const std::ptrdiff_t found = find_codepoint(codepoint, fold.map);
        if (found < 0)
            continue;
        const auto index = static_cast<std::size_t>(found);
        FoldedCodepoints out;
        out.count = fold.width;
        for (std::size_t i = 0; i < fold.width; ++i)
            out.codepoints[i] = fold.data[index * fold.width + i];
        // Aralık kaydı: ilk kod noktası aralıktaki yere göre kayar. Verinin alt ucu aralığın alt ucundan bir
        // fazlaysa aralık "büyük, küçük" çiftlerinden oluşur.
        if (fold.map[index] != codepoint) {
            const std::uint32_t low = fold.map[index] & kValue;
            if (low + 1 == out.codepoints[0])
                out.codepoints[0] = codepoint + ((codepoint & 1) == (low & 1) ? 1 : 0);
            else
                out.codepoints[0] += codepoint - low;
        }
        return out;
    }
    return {{codepoint}, 1};
}


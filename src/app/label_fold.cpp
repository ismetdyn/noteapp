struct FoldMap {
    std::span<const std::uint32_t> map;
    std::span<const std::uint32_t> data;
    std::size_t width;
};

constexpr FoldMap kMaps[] = {{kMap1, kData1, 1}, {kMap2, kData2, 2}, {kMap3, kData3, 3}};

// md_unicode_bsearch__: bulunan kaydın konumu (aralıkta alt ucu), yoksa -1.
std::ptrdiff_t find_codepoint(char32_t codepoint, std::span<const std::uint32_t> map) {
    std::ptrdiff_t begin = 0;
    std::ptrdiff_t end = static_cast<std::ptrdiff_t>(map.size()) - 1;
    while (begin <= end) {
        std::ptrdiff_t pivot_begin = (begin + end) / 2;
        std::ptrdiff_t pivot_end = pivot_begin;
        if (map[static_cast<std::size_t>(pivot_end)] & kFrom)
            ++pivot_end;
        if (map[static_cast<std::size_t>(pivot_begin)] & kTo)
            --pivot_begin;
        if (codepoint < (map[static_cast<std::size_t>(pivot_begin)] & kValue))
            end = pivot_begin - 1;
        else if (codepoint > (map[static_cast<std::size_t>(pivot_end)] & kValue))
            begin = pivot_end + 1;
        else
            return pivot_begin;
    }
    return -1;
}


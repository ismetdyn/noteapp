int run_completion(const ParsedArgs& args) {
    const std::string_view shell = args.rest.size() == 1 ? std::string_view(args.rest.front()) : "";
    if (shell == "zsh") {
        std::cout << zsh_script();
    } else if (shell == "bash") {
        std::cout << bash_script();
    } else if (shell == "fish") {
        std::cout << fish_script();
    } else {
        std::cerr << core::tr("cli.completion_usage") << '\n';
        return kExitUsage;
    }
    return kExitOk;
}

// Çıktı satır başına bir aday. Bilinmeyen tür ya da eksik argüman kullanım hatasıdır (betik hatası); sessizdir:
// stderr Tab'da istemin ortasına basılırdı.
int run_complete(const ParsedArgs& args, const core::Config& config) {
    if (args.rest.empty() || args.rest.size() > 2)
        return kExitUsage;
    const std::string& kind = args.rest.front();
    const std::string_view prefix = args.rest.size() == 2 ? std::string_view(args.rest[1]) : "";
    std::vector<std::string> candidates;
    if (kind == "query") {
        candidates = query_candidates(prefix, config);
    } else {
        std::optional<std::vector<std::string>> values = values_of(kind, config);
        if (!values)
            return kExitUsage;
        std::erase_if(*values, [&](const std::string& value) { return !value.starts_with(prefix); });
        candidates = std::move(*values);
    }
    std::string out;
    for (const std::string& candidate : candidates) {
        if (is_completion_safe(candidate))
            out += candidate + '\n';
    }
    std::cout << out;
    return kExitOk;
}


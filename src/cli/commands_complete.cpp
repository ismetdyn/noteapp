// Betiklerdeki tür adı. Depodan gelenler `note __complete` türüyle aynıdır; file/directory'yi kabuk tamamlar,
// text/none tamamlanmaz.
std::string_view kind_name(ValueKind kind) {
    switch (kind) {
    case ValueKind::None:
        return "none";
    case ValueKind::Text:
        return "text";
    case ValueKind::Note:
        return "note";
    case ValueKind::Folder:
        return "folder";
    case ValueKind::Type:
        return "type";
    case ValueKind::View:
        return "view";
    case ValueKind::ConfigKey:
        return "config-key";
    case ValueKind::Query:
        return "query";
    case ValueKind::Command:
        return "command";
    case ValueKind::File:
        return "file";
    case ValueKind::Directory:
        return "directory";
    }
    return "none";
}

// Komut satırında bir konum: kök (alt komutsuz hızlı ekleme), fiilsiz komut ya da "komut fiil".
struct Context {
    std::string name;  // "" kök, "ls", "sync init"
    std::span<const OptionSpec> options;
    ValueKind operand;
};

std::vector<Context> contexts() {
    std::vector<Context> out{{"", kAddOptions, ValueKind::Text}};
    for (const CommandSpec& command : kCommands) {
        if (command.verbs.empty())
            out.push_back({std::string(command.name), command.options, command.operand});
        for (const VerbSpec& verb : command.verbs)
            out.push_back({std::string(command.name) + " " + std::string(verb.name), verb.options, verb.operand});
    }
    return out;
}

// Menüde görünen açıklama kullanıcının dilindedir; tek satır olmalı (katalog bizim, yine de satır sonu
// betiği bozmasın).
std::string describe(std::string_view key) {
    std::string text = core::tr(key);
    std::ranges::replace(text, '\n', ' ');
    return text;
}

// POSIX tek tırnak (bash, zsh): içerik aynen kalır, yalnız ' kapatılıp kaçışla yeniden açılır.
std::string sh_quote(std::string_view text) {
    std::string out = "'";
    for (const char c : text)
        out += c == '\'' ? std::string("'\\''") : std::string(1, c);
    return out + "'";
}

// fish tek tırnağında yalnız \ ve ' kaçışlıdır.
std::string fish_quote(std::string_view text) {
    std::string out = "'";
    for (const char c : text) {
        if (c == '\'' || c == '\\')
            out += '\\';
        out += c;
    }
    return out + "'";
}

std::string join(const std::vector<std::string>& parts, std::string_view separator) {
    std::string out;
    for (const std::string& part : parts)
        out += (out.empty() ? "" : std::string(separator)) + part;
    return out;
}

std::vector<std::string> all_command_names() {
    std::vector<std::string> names;
    for (const CommandSpec& command : kCommands)
        names.emplace_back(command.name);
    return names;
}

std::vector<std::string> command_names(bool with_verbs) {
    std::vector<std::string> names;
    for (const CommandSpec& command : kCommands)
        if (command.verbs.empty() != with_verbs)
            names.emplace_back(command.name);
    return names;
}

std::vector<std::string> option_names(const OptionSpec& option) {
    std::vector<std::string> names{std::string(option.name)};
    if (!option.alias.empty())
        names.emplace_back(option.alias);
    return names;
}

// ---- zsh ----

// _describe öğesi "ad:açıklama"; addaki ':' kaçışlıdır.
std::string zsh_item(std::string_view name, std::string_view description_key) {
    std::string escaped;
    for (const char c : name) {
        if (c == ':')
            escaped += '\\';
        escaped += c;
    }
    return sh_quote(escaped + ":" + describe(description_key));
}

std::string zsh_patterns(const std::vector<std::string>& names) {
    std::vector<std::string> quoted;
    for (const std::string& name : names)
        quoted.push_back(sh_quote(name));
    return join(quoted, "|");
}

std::string zsh_script() {
    std::string out = R"SH(#compdef note
# zsh completion for note. Generated by `note completion zsh`; regenerate after upgrading note.

__note_values() {
  local kind=$1 prefix= line ret=1
  local -a keys items
  if [[ $kind == query ]]; then prefix=${(Q)PREFIX}; fi
  for line in "${(@f)$(command note __complete $kind "$prefix" 2>/dev/null)}"; do
    if [[ -z $line ]]; then continue; fi
    if [[ $kind == query && $line == *: ]]; then keys+=("$line"); else items+=("$line"); fi
  done
  if (( $#keys )); then compadd -S '' -- "${keys[@]}" && ret=0; fi
  if (( $#items )); then compadd -- "${items[@]}" && ret=0; fi
  return ret
}

__note_commands() {
  local -a list
  list=()SH";
    for (const CommandSpec& command : kCommands)
        out += "\n    " + zsh_item(command.name, command.description);
    out += R"SH()
  _describe -t commands command list
}

__note_value() {
  case $1 in
    (file) _files ;;
    (directory) _files -/ ;;
    (command) __note_commands ;;
    (text|none) return 1 ;;
    (*) __note_values $1 ;;
  esac
}

_note() {
  local cmd=${words[2]} prev=${words[CURRENT-1]} ctx=
  local -a list
  if (( CURRENT == 2 )) && [[ $PREFIX != -* ]]; then
    __note_commands
    return
  fi
  if (( CURRENT > 2 )); then
    case $cmd in
      ()SH" + zsh_patterns(command_names(false)) +
           R"SH() ctx=$cmd ;;
      ()SH" + zsh_patterns(command_names(true)) +
           R"SH()
        if (( CURRENT == 3 )); then
          case $cmd in)SH";
    for (const CommandSpec& command : kCommands) {
        if (command.verbs.empty())
            continue;
        out += "\n            (" + sh_quote(command.name) + ") list=(";
        for (const VerbSpec& verb : command.verbs)
            out += "\n                " + zsh_item(verb.name, verb.description);
        out += ") ;;";
    }
    out += R"SH(
          esac
          _describe -t commands verb list
          return
        fi
        ctx="$cmd ${words[3]}" ;;
    esac
  fi
  case $ctx in)SH";
    for (const Context& context : contexts()) {
        out += "\n    (" + sh_quote(context.name) + ")";
        std::string values;
        for (const OptionSpec& option : context.options) {
            if (option.value != ValueKind::None)
                values += "\n        (" + zsh_patterns(option_names(option)) + ") __note_value " +
                          std::string(kind_name(option.value)) + "; return ;;";
        }
        if (!values.empty())
            out += "\n      case $prev in" + values + "\n      esac";
        if (!context.options.empty()) {
            out += "\n      if [[ $PREFIX == -* ]]; then\n        list=(";
            for (const OptionSpec& option : context.options)
                for (const std::string& name : option_names(option))
                    out += "\n          " + zsh_item(name, option.description);
            out += ")\n        _describe -o option list\n        return\n      fi";
        }
        out += "\n      __note_value " + std::string(kind_name(context.operand)) + " ;;";
    }
    out += R"SH(
  esac
}

if [[ $funcstack[1] == _note ]]; then _note "$@"; else compdef _note note; fi
)SH";
    return out;
}

// ---- bash ----

std::string bash_words(const std::vector<std::string>& words) {
    std::vector<std::string> quoted;
    for (const std::string& word : words)
        quoted.push_back(sh_quote(word));
    return "__note_words " + join(quoted, " ");
}

std::string bash_script() {
    std::string out = R"SH(# bash completion for note. Generated by `note completion bash`; regenerate after upgrading note.

__note_words() {
  local word
  for word in "$@"; do
    if [[ $word == "$cur"* ]]; then COMPREPLY+=("$word"); fi
  done
}

__note_value() {
  local line
  case $1 in
    file)
      compopt -o filenames 2>/dev/null
      while IFS= read -r line; do COMPREPLY+=("$line"); done < <(compgen -f -- "$cur") ;;
    directory)
      compopt -o filenames 2>/dev/null
      while IFS= read -r line; do COMPREPLY+=("$line"); done < <(compgen -d -- "$cur") ;;
    command) )SH" + bash_words(all_command_names()) +
                      R"SH( ;;
    text|none) ;;
    *)
      if [[ $1 != query ]]; then compopt -o filenames 2>/dev/null; fi
      while IFS= read -r line; do
        if [[ -n $line && $line == "$cur"* ]]; then COMPREPLY+=("$line"); fi
      done < <(command note __complete "$1" "$cur" 2>/dev/null) ;;
  esac
}

_note() {
  COMPREPLY=()
  # readline 'tag:pr'yi COMP_WORDBREAKS'teki ':' ile 'tag' ':' 'pr' diye böler: sözcük yeniden birleştirilir.
  local i=$COMP_CWORD cur=${COMP_WORDS[COMP_CWORD]}
  while (( i > 1 )) && [[ ${COMP_WORDS[i]} == : || ${COMP_WORDS[i-1]} == : ]]; do
    (( i-- ))
    cur=${COMP_WORDS[i]}$cur
  done
  cur=${cur//\\/}
  cur=${cur#[\"\']}
  local prev=${COMP_WORDS[i-1]} cmd=${COMP_WORDS[1]} ctx=
  if (( i == 1 )) && [[ $cur != -* ]]; then
    __note_value command
    return 0
  fi
  if (( i > 1 )); then
    case $cmd in
      )SH" + join(command_names(false), "|") +
                      R"SH() ctx=$cmd ;;
      )SH" + join(command_names(true), "|") +
                      R"SH()
        if (( i == 2 )); then
          case $cmd in)SH";
    for (const CommandSpec& command : kCommands) {
        if (command.verbs.empty())
            continue;
        std::vector<std::string> verbs;
        for (const VerbSpec& verb : command.verbs)
            verbs.emplace_back(verb.name);
        out += "\n            " + std::string(command.name) + ") " + bash_words(verbs) + " ;;";
    }
    out += R"SH(
          esac
          return 0
        fi
        ctx="$cmd ${COMP_WORDS[2]}" ;;
    esac
  fi
  case $ctx in)SH";
    for (const Context& context : contexts()) {
        out += "\n    " + sh_quote(context.name) + ")\n      case $prev in";
        std::vector<std::string> names;
        for (const OptionSpec& option : context.options) {
            std::ranges::move(option_names(option), std::back_inserter(names));
            if (option.value != ValueKind::None)
                out += "\n        " + join(option_names(option), "|") + ") __note_value " +
                       std::string(kind_name(option.value)) + " ;;";
        }
        out += "\n        *)";
        if (!names.empty())
            out += "\n          if [[ $cur == -* ]]; then " + bash_words(names) + "; return 0; fi";
        out += "\n          __note_value " + std::string(kind_name(context.operand)) + " ;;\n      esac ;;";
    }
    out += R"SH(
  esac
  # readline yalnız son ':' sonrasını değiştirir.
  if [[ $cur == *:* && $COMP_WORDBREAKS == *:* ]]; then
    local strip=${cur%"${cur##*:}"} k
    for k in "${!COMPREPLY[@]}"; do COMPREPLY[k]=${COMPREPLY[k]#"$strip"}; done
  fi
  if (( ${#COMPREPLY[@]} == 1 )) && [[ ${COMPREPLY[0]} == *: ]]; then compopt -o nospace 2>/dev/null; fi
  return 0
}

complete -F _note note
)SH";
    return out;
}

// ---- fish ----

std::string fish_option(std::string_view name) {
    if (name.starts_with("--"))
        return "-l " + std::string(name.substr(2));
    return (name.size() == 2 ? "-s " : "-o ") + std::string(name.substr(1));
}

// Seçeneğin ya da konumlu argümanın fish bayrakları.
std::string fish_value(ValueKind kind, bool option) {
    switch (kind) {
    case ValueKind::None:
        return "";
    case ValueKind::Text:
        return option ? " -x" : "";
    case ValueKind::File:
    case ValueKind::Directory:
        return option ? " -r -F" : " -F";
    case ValueKind::Command:
        return std::string(option ? " -x" : "") + " -a " + fish_quote(join(all_command_names(), " "));
    case ValueKind::Query:
        return std::string(option ? " -x" : "") + " -a '(__note_values query (commandline -ct))'";
    case ValueKind::Note:
    case ValueKind::Folder:
    case ValueKind::Type:
    case ValueKind::View:
    case ValueKind::ConfigKey:
        return std::string(option ? " -x" : "") + " -a '(__note_values " + std::string(kind_name(kind)) + ")'";
    }
    return "";
}

std::string fish_script() {
    std::string out = R"SH(# fish completion for note. Generated by `note completion fish`; regenerate after upgrading note.

function __note_tokens
    commandline -xpc 2>/dev/null
    or commandline -opc
end

function __note_in_add
    set -l tokens (__note_tokens)
    test (count $tokens) -eq 1; and return 0
    not contains -- $tokens[2] )SH" + join(all_command_names(), " ") +
                      R"SH(
end

function __note_needs_command
    test (count (__note_tokens)) -eq 1
end

function __note_needs_verb
    set -l tokens (__note_tokens)
    test (count $tokens) -eq 2; and test "$tokens[2]" = "$argv[1]"
end

function __note_in
    set -l tokens (__note_tokens)
    test (count $tokens) -gt (count $argv); or return 1
    test "$tokens[2]" = "$argv[1]"; or return 1
    test (count $argv) -eq 1; or test "$tokens[3]" = "$argv[2]"
end

function __note_values
    command note __complete $argv 2>/dev/null
end

complete -c note -f
)SH";
    for (const CommandSpec& command : kCommands)
        out += "complete -c note -n __note_needs_command -a " + fish_quote(command.name) + " -d " +
               fish_quote(describe(command.description)) + "\n";
    for (const CommandSpec& command : kCommands)
        for (const VerbSpec& verb : command.verbs)
            out += "complete -c note -n " + fish_quote("__note_needs_verb " + std::string(command.name)) + " -a " +
                   fish_quote(verb.name) + " -d " + fish_quote(describe(verb.description)) + "\n";
    for (const Context& context : contexts()) {
        const std::string condition =
            context.name.empty() ? std::string("__note_in_add") : fish_quote("__note_in " + context.name);
        for (const OptionSpec& option : context.options) {
            std::string names;
            for (const std::string& name : option_names(option))
                names += " " + fish_option(name);
            out += "complete -c note -n " + condition + names + fish_value(option.value, true) + " -d " +
                   fish_quote(describe(option.description)) + "\n";
        }
        if (!context.name.empty() && context.operand != ValueKind::None && context.operand != ValueKind::Text)
            out += "complete -c note -n " + condition + fish_value(context.operand, false) + "\n";
    }
    return out;
}

// ---- __complete ----

// Tamamlama her Tab'da çalışır ve hiçbir şey yazmamalı: depo yoksa kurulmaz (okuma yolu dosya yaratmaz),
// eski notlar geçiş bekliyorsa açılmaz, açılışın türetilmiş dizin onarımı (yazma) atlanır. Açılamayan, bozuk
// ya da kilitli depo boş liste verir.
std::optional<core::NoteStore> read_only_store(const core::Config& config) {
    if (core::legacy_notes_pending(config.notes_dir, core::data_dir()))
        return std::nullopt;
    core::NoteStore store = core::NoteStore::for_config(config);
    store.impl().derived_checked = true;
    return store;
}

// Türün tüm değerleri; bilinmeyen tür nullopt.
std::optional<std::vector<std::string>> values_of(std::string_view kind, const core::Config& config) {
    if (kind == "type")
        return config.types;
    std::vector<std::string> out;
    if (kind == "config-key") {
        for (auto& entry : all_entries(config))
            out.push_back(std::move(entry.first));
        return out;
    }
    if (kind != "note" && kind != "folder" && kind != "tag" && kind != "view")
        return std::nullopt;
    const std::optional<core::NoteStore> store = read_only_store(config);
    if (!store)
        return out;
    if (kind == "note") {
        for (const core::NoteInfo& note : store->list())
            out.push_back(note.path.string());
    } else if (kind == "folder") {
        out = store->folders();
    } else if (kind == "tag") {
        for (const core::TagCount& tag : store->tags())
            out.push_back(tag.display);
    } else if (const auto views = core::list_views(*store)) {
        for (const core::SavedView& view : *views)
            out.push_back(view.name);
    }
    return out;
}

// Sorgunun son sözcüğü tamamlanır, öncesi (tırnaklı çok sözcüklü sorgu) aynen kalır: iki noktasız sözcükte
// anahtar adları, `tag:` `type:` `in:` `view:` sonrasında değerler. Değere göre süzülmez: eşleştirme kabuğun
// (büyük/küçük harf duyarsız zsh matcher'ı, fzf-tab) işidir.
std::vector<std::string> query_candidates(std::string_view prefix, const core::Config& config) {
    const std::size_t space = prefix.find_last_of(" \t");
    const std::string head(space == std::string_view::npos ? std::string_view() : prefix.substr(0, space + 1));
    const std::string_view token = space == std::string_view::npos ? prefix : prefix.substr(space + 1);
    std::vector<std::string> out;
    const std::size_t colon = token.find(':');
    if (colon == std::string_view::npos) {
        for (const std::string_view name : search::query_key_names())
            out.push_back(head + std::string(name) + ":");
        return out;
    }
    const std::string key(token.substr(0, colon));
    const std::string_view kind = key == "tag"    ? "tag"
                                  : key == "type" ? "type"
                                  : key == "in"   ? "folder"
                                  : key == "view" ? "view"
                                                  : "";
    if (kind.empty())
        return out;
    for (const std::string& value : values_of(kind, config).value_or(std::vector<std::string>{}))
        out.push_back(head + key + ":" + value);
    return out;
}

